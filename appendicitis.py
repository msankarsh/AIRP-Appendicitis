image_records = []
for filename in os.listdir(image_dir):

    # Only process bmp files
    if not filename.lower().endswith(".bmp"):
        continue

    filepath = os.path.join(image_dir, filename)

    # Expected format:
    # {pid}.{im_number} {description}.bmp
    #
    # Example:
    # 123.4 Abdomen transverse.bmp

    match = re.match(
        r"^(\d+)\.(\d+)\s*(.*?)\.bmp$",
        filename,
        flags=re.IGNORECASE
    )

    if match:
        pid = int(match.group(1))
        image_number = int(match.group(2))
        description = match.group(3).strip()

    else:
        # Handle unexpected filenames
        # Try to at least recover the patient ID
        fallback = re.match(r"^(\d+)", filename)

        if fallback:
            pid = int(fallback.group(1))
        else:
            pid = None

        image_number = None
        description = filename.replace(".bmp", "")

    image_records.append({
        "pid": pid,
        "image_number": image_number,
        "description": description,
        "filename": filename
    })

