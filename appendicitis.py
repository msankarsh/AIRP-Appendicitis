# Define a wrapper class for model2 to explicitly handle flattening
class GradCamModel(nn.Module):
    def __init__(self, original_model):
        super(GradCamModel, self).__init__()
        # Separate the convolutional layers (features) from the linear layers (classifier)
        # model2 layers (0-14) are features, (16-17) are classifier layers with Flatten (15) in between
        self.features = nn.Sequential(*original_model[:15]) # Layers up to (and including) the last MaxPool2d
        self.classifier_start = original_model[16] # The first Linear layer
        self.classifier_end = original_model[17]   # The second Linear layer

    def forward(self, x):
        x = self.features(x)
        x = x.flatten(1) # Manually flatten the tensor after features
        x = self.classifier_start(x)
        x = self.classifier_end(x)
        return x

